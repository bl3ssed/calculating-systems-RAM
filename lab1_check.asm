.text
.globl main

main:
    li a7, 5          # системный вызов: чтение целого числа
    ecall

    li t1, 14         # <--- ЗДЕСЬ: 14 = номер студента
    sub t2, a0, t1    # вычисляем разницу: x - 14
    seqz a0, t2       # если разница 0, a0 становится 1, иначе 0

    li a7, 1          # системный вызов: печать результата
    ecall

    li a7, 10         # выход из программы
    ecall