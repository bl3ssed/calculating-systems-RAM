#Программа: заполнение массива из 30 чисел (16+14)
#Остановка: считали 30 или ввели 0
.data
my_array: .space 120      # <--- ЗДЕСЬ: 120 байт = 30 элементов * 4 байта

.text
.globl main

main:
    la t0, my_array       # t0 = указатель на начало массива
    li t1, 0              # t1 = счетчик считанных элементов
    li t2, 30             # <--- ЗДЕСЬ: 30 = лимит (16 + 14)

read_loop:
    li a7, 5              # читаем число
    ecall

    beqz a0, finish       # если ввели 0, завершаем

    sw a0, 0(t0)          # сохраняем число в массив
    addi t0, t0, 4        # сдвигаем указатель на 4 байта
    addi t1, t1, 1        # увеличиваем счетчик

    blt t1, t2, read_loop # продолжаем, если счетчик < 30

finish:
    li a7, 10             # выход
    ecall